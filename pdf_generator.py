"""
PackAssist - Professional one-page "Pack Report" PDF generator (Pack Studio style).

Produces a single A4 sheet containing:
    - Header: part info (name, dims, weight) + PackAssist branding
    - Hero: large isometric render of the packed box
    - Metrics: clean grid of key numbers
    - Small multi-views: top / front / side
    - Cost summary (only when cost data is present)

Standalone: python pdf_generator.py [input.json] [output.pdf]
Requires:  fpdf2  (pip install fpdf2)
"""

